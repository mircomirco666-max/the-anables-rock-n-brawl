const GLYPH_ORDER = Object.keys(GLYPHS);
const GLYPH_INDEX = {}; GLYPH_ORDER.forEach((k, i) => GLYPH_INDEX[k] = i);
const _fontCache = new Map();

function normText(s) {
  return String(s).toUpperCase()
    .replace(/[ÈÉ]/g, "E'").replace(/À/g, "A'").replace(/Ì/g, "I'").replace(/Ò/g, "O'").replace(/Ù/g, "U'");
}
function fontSheet(color) {
  let c = _fontCache.get(color);
  if (c) return c;
  const n = GLYPH_ORDER.length;
  const pb = new PixBuf(n * 6, 7);
  const cc = col(color);
  GLYPH_ORDER.forEach((k, gi) => {
    const g = GLYPHS[k];
    for (let y = 0; y < 7; y++) for (let x = 0; x < 5; x++) if (g[y][x] === '#') pb.set(gi * 6 + x, y, cc);
  });
  c = pb.toCanvas();
  _fontCache.set(color, c);
  return c;
}
function textWidth(s, scale = 1) { return normText(s).length * 6 * scale - scale; }

// opts: {align:'left'|'center'|'right', shadow:'#hex', scale:1, outline:'#hex'}
// le scritte già composte restano in memoria: un solo drawImage invece di uno per lettera (e 9 col contorno)
const _textCache = new Map();
function drawText(ctx, s, x, y, color = '#ffffff', opts = {}) {
  const t = normText(s);
  const sc = opts.scale || 1;
  const w = t.length * 6 * sc - sc;
  let x0 = Math.round(opts.align === 'center' ? x - w / 2 : opts.align === 'right' ? x - w : x);
  y = Math.round(y);
  if (t.length && !opts.noCache) {
    const key = t + '|' + color + '|' + sc + '|' + (opts.outline || '') + '|' + (opts.shadow || '');
    let c = _textCache.get(key);
    if (!c) {
      if (_textCache.size > 700) _textCache.clear();
      const [cv, cx] = makeCanvas(w + sc * 3, 7 * sc + sc * 3);
      drawText(cx, s, sc, sc, color, Object.assign({}, opts, { align: 'left', noCache: true }));
      c = cv; _textCache.set(key, c);
    }
    ctx.drawImage(c, x0 - sc, y - sc, c.width, c.height);
    return w;
  }
  const draw = (clr, ox, oy) => {
    const sheet = fontSheet(clr);
    for (let i = 0; i < t.length; i++) {
      const gi = GLYPH_INDEX[t[i]];
      if (gi === undefined || t[i] === ' ') continue;
      ctx.drawImage(sheet, gi * 6, 0, 5, 7, x0 + i * 6 * sc + ox, y + oy, 5 * sc, 7 * sc);
    }
  };
  if (opts.outline) {
    const o = sc;
    for (const [ox, oy] of [[-o, 0], [o, 0], [0, -o], [0, o], [-o, -o], [o, o], [-o, o], [o, -o]]) draw(opts.outline, ox, oy);
  }
  if (opts.shadow) draw(opts.shadow, sc, sc);
  draw(color, 0, 0);
  return w;
}
